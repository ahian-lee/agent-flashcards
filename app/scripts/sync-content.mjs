#!/usr/bin/env node
/**
 * Content sync: `../content/decks/*.json` -> `src/content/decks/` + a generated
 * `src/content/index.ts` of static imports (bundler-friendly, no glob at runtime).
 *
 * Design goals
 *  - Never break the build: missing `content/`, unreadable files or malformed
 *    JSON become warnings and the committed fallback decks keep the app usable.
 *  - The script only *copies*; all normalisation lives in `src/lib/content.ts`
 *    so the same code path is covered by unit tests.
 *
 * Usage: node scripts/sync-content.mjs
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const appRoot = resolve(here, '..')
const repoRoot = resolve(appRoot, '..')
const contentRoot = join(repoRoot, 'content')

const decksTarget = join(appRoot, 'src', 'content', 'decks')
const fallbackDir = join(appRoot, 'src', 'content', 'fallback')
const indexTarget = join(appRoot, 'src', 'content', 'index.ts')

const warnings = []

function warn(message) {
  warnings.push(message)
  console.warn(`  ! ${message}`)
}

function slugifyFilename(file) {
  return file
    .replace(/\.json$/i, '')
    .toLowerCase()
    .replace(/[^\w\u4e00-\u9fa5-]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

/** Find the first directory that actually contains deck JSON files. */
function findDeckSource() {
  const candidates = [join(contentRoot, 'decks'), contentRoot]
  for (const candidate of candidates) {
    if (!existsSync(candidate)) continue
    let files = []
    try {
      files = readdirSync(candidate).filter((file) => file.toLowerCase().endsWith('.json'))
    } catch {
      continue
    }
    if (files.length > 0) return { dir: candidate, files }
  }
  return null
}

function readDeck(filePath) {
  try {
    const parsed = JSON.parse(readFileSync(filePath, 'utf8'))
    if (!parsed || typeof parsed !== 'object') throw new Error('顶层不是对象')
    return parsed
  } catch (error) {
    warn(`跳过无法解析的文件：${filePath}（${error.message}）`)
    return null
  }
}

function describeDeck(deck, file) {
  const cards = Array.isArray(deck.cards) ? deck.cards : Array.isArray(deck.items) ? deck.items : []
  const types = {}
  for (const card of cards) {
    const type = typeof card?.type === 'string' ? card.type : '?'
    types[type] = (types[type] ?? 0) + 1
  }
  const typeSummary = Object.entries(types)
    .map(([type, count]) => `${type}:${count}`)
    .join(' ')
  console.log(`  - ${file.padEnd(28)} ${String(cards.length).padStart(3)} 张  ${typeSummary}`)
}

const source = findDeckSource()
rmSync(decksTarget, { recursive: true, force: true })
mkdirSync(decksTarget, { recursive: true })

const copied = []
if (source) {
  console.log(`读取内容源：${source.dir}`)
  for (const file of source.files.sort()) {
    const from = join(source.dir, file)
    const deck = readDeck(from)
    if (!deck) continue
    copyFileSync(from, join(decksTarget, file))
    describeDeck(deck, file)
    copied.push({ file, idHint: slugifyFilename(file) })
  }
} else {
  warn('未找到 ../content/decks/*.json，本次仅使用内置兜底内容。')
}

if (copied.length === 0) {
  console.warn('  ! 没有可用的真实内容，应用将展示 src/content/fallback 下的兜底 deck。')
}

// ------------------------------------------------------------------ fallback
const fallbackFiles = existsSync(fallbackDir)
  ? readdirSync(fallbackDir)
      .filter((file) => file.toLowerCase().endsWith('.json'))
      .sort()
  : []
if (fallbackFiles.length === 0) warn('src/content/fallback 下没有兜底 deck，离线首装可能看不到内容。')

// -------------------------------------------------------------- index.ts
const lines = []
lines.push('// AUTO-GENERATED by scripts/sync-content.mjs — do not edit by hand.')
lines.push(`// Real decks: ${copied.length} file(s) from content/decks · fallback decks: ${fallbackFiles.length}.`)
lines.push('// Re-generate with: npm run sync:content')
lines.push("import { buildDecks } from '../lib/content'")
lines.push('')

copied.forEach((entry, index) => {
  lines.push(`import real${index} from ${JSON.stringify(`./decks/${entry.file}`)}`)
})
fallbackFiles.forEach((file, index) => {
  lines.push(`import fallback${index} from ${JSON.stringify(`./fallback/${file}`)}`)
})
if (copied.length > 0 || fallbackFiles.length > 0) lines.push('')

lines.push('const built = buildDecks(')
lines.push('  [')
for (const [index, entry] of copied.entries()) {
  lines.push(`    { raw: real${index}, idHint: ${JSON.stringify(entry.idHint)} },`)
}
lines.push('  ],')
lines.push('  [')
for (const [index, file] of fallbackFiles.entries()) {
  lines.push(`    { raw: fallback${index}, idHint: ${JSON.stringify(slugifyFilename(file))} },`)
}
lines.push('  ],')
lines.push(')')
lines.push('')
lines.push('export const decks = built.decks')
lines.push('export const contentSource = built.source')
lines.push('')

writeFileSync(indexTarget, lines.join('\n'), 'utf8')

console.log('')
console.log(`已生成 ${indexTarget.replace(repoRoot + '\\', '')}`)
console.log(`真实 deck：${copied.length} 个 · 兜底 deck：${fallbackFiles.length} 个 · 警告：${warnings.length}`)
if (warnings.length > 0) {
  console.log('提示：警告不会阻断构建，应用会自动回退到可用内容。')
}
